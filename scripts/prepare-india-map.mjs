/**
 * Convert the topology-simplified geoBoundaries IND ADM1 geometry to SVG paths.
 * See docs/design/india-map-provenance.md for the pinned source and preparation.
 * Usage: node scripts/prepare-india-map.mjs /path/to/india-display.geojson
 * This is an offline build-time utility; the exhibition needs no GIS dependency.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) throw new Error("Supply the topology-simplified GeoJSON path.");
const collection = JSON.parse(readFileSync(input, "utf8"));
const width = 640;
const height = 720;
const padding = 18;
const radians = Math.PI / 180;
const centerLongitude = 82 * radians;
const centerLatitude = 23 * radians;
const unionTerritories = new Set(["IN-AN", "IN-CH", "IN-DH", "IN-DL", "IN-JK", "IN-LA", "IN-LD", "IN-PY"]);
const currentIds = { "IN-CT": "IN-CG", "IN-OR": "IN-OD", "IN-TG": "IN-TS", "IN-UT": "IN-UK" };

// Spherical Lambert azimuthal equal-area projection, centred on India.
function project([longitude, latitude]) {
  const lambda = longitude * radians - centerLongitude;
  const phi = latitude * radians;
  const k = Math.sqrt(2 / (1 + Math.sin(centerLatitude) * Math.sin(phi) + Math.cos(centerLatitude) * Math.cos(phi) * Math.cos(lambda)));
  return [k * Math.cos(phi) * Math.sin(lambda), -k * (Math.cos(centerLatitude) * Math.sin(phi) - Math.sin(centerLatitude) * Math.cos(phi) * Math.cos(lambda))];
}

const projected = collection.features.map(({ properties, geometry }) => {
  if (!["Polygon", "MultiPolygon"].includes(geometry.type)) throw new Error(`Unexpected geometry: ${geometry.type}`);
  const polygons = geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  return {
    id: currentIds[properties.shapeISO] ?? properties.shapeISO,
    name: properties.shapeName.normalize("NFD").replace(/[\u0300-\u036f]/g, ""),
    polygons: polygons.map((polygon) => polygon.map((ring) => ring.map(project))),
  };
});

const allPoints = projected.flatMap(({ polygons }) => polygons.flat(2));
const minimumX = Math.min(...allPoints.map(([x]) => x));
const maximumX = Math.max(...allPoints.map(([x]) => x));
const minimumY = Math.min(...allPoints.map(([, y]) => y));
const maximumY = Math.max(...allPoints.map(([, y]) => y));
const scale = Math.min((width - padding * 2) / (maximumX - minimumX), (height - padding * 2) / (maximumY - minimumY));
const offsetX = (width - (maximumX - minimumX) * scale) / 2;
const offsetY = (height - (maximumY - minimumY) * scale) / 2;
const fit = ([x, y]) => [Number(((x - minimumX) * scale + offsetX).toFixed(2)), Number(((y - minimumY) * scale + offsetY).toFixed(2))];

function signedArea(ring) {
  return ring.reduce((sum, point, index) => {
    const next = ring[(index + 1) % ring.length];
    return sum + point[0] * next[1] - next[0] * point[1];
  }, 0) / 2;
}

function centroid(ring) {
  const area = signedArea(ring);
  let x = 0;
  let y = 0;
  ring.forEach((point, index) => {
    const next = ring[(index + 1) % ring.length];
    const cross = point[0] * next[1] - next[0] * point[1];
    x += (point[0] + next[0]) * cross;
    y += (point[1] + next[1]) * cross;
  });
  return { x: Number((x / (6 * area)).toFixed(2)), y: Number((y / (6 * area)).toFixed(2)) };
}

const regions = projected.map(({ id, name, polygons }) => {
  const fitted = polygons.map((polygon) => polygon.map((ring) => ring.map(fit)));
  const largest = fitted.map(([outer]) => outer).sort((a, b) => Math.abs(signedArea(b)) - Math.abs(signedArea(a)))[0];
  const path = fitted.flatMap((polygon) => polygon.map((ring) => {
    const points = ring.filter((point, index) => index === 0 || point[0] !== ring[index - 1][0] || point[1] !== ring[index - 1][1]);
    return `M${points.map((point) => point.join(",")).join("L")}Z`;
  })).join("");
  return { id, name, kind: unionTerritories.has(id) ? "union-territory" : "state", path, label: centroid(largest) };
}).sort((a, b) => a.name.localeCompare(b.name, "en"));

if (regions.length !== 36 || new Set(regions.map(({ id }) => id)).size !== 36) throw new Error("Expected 36 unique regions.");
if (regions.filter(({ kind }) => kind === "state").length !== 28) throw new Error("Expected 28 states.");
if (regions.some(({ path, label }) => !path || !Number.isFinite(label.x) || !Number.isFinite(label.y))) throw new Error("Invalid path or label.");

const output = `// Generated by scripts/prepare-india-map.mjs. Do not hand-edit geographic boundaries.
// DataMeet India community / Election Commission of India via geoBoundaries.
// CC BY 2.5 IN; source, transformations and limitations: docs/design/india-map-provenance.md.
export type IndiaMapRegion = {
  id: string;
  name: string;
  kind: "state" | "union-territory";
  path: string;
  label: { x: number; y: number };
};

export const INDIA_MAP_VIEWBOX = "0 0 ${width} ${height}";
export const INDIA_MAP_SOURCE = {
  label: "DataMeet / geoBoundaries",
  url: "https://www.geoboundaries.org/api/current/gbOpen/IND/ADM1/",
  license: "CC BY 2.5 IN",
  licenseUrl: "https://creativecommons.org/licenses/by/2.5/in/",
} as const;

export const indiaMapRegions: IndiaMapRegion[] = ${JSON.stringify(regions, null, 2)};
`;
const destination = fileURLToPath(new URL("../content/india-map.ts", import.meta.url));
writeFileSync(destination, output);
console.log(`Prepared ${regions.length} regions (${Buffer.byteLength(output)} bytes) at ${destination}`);
